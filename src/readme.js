import { ROWS, SECTION_HEADS } from './layout.js';
import { urlLabel } from './page.js';
import { num } from './activity.js';

const plain = (s) => String(s).replace(/\*\*(.+?)\*\*/g, '$1').replace(/\*(.+?)\*/g, '$1').replace(/(^|[\s(])_(.+?)_(?=$|[\s.,;:!?)])/g, '$1$2');
const attr = (s) => String(s).replace(/\s+/g, ' ').replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const end = (s) => (/[.!?…”]$/.test(s) ? s : `${s}.`);
const join = (...parts) => parts.filter(Boolean).map((p) => end(plain(p).replace(/\s+/g, ' ').trim())).join(' ');

/** Where each piece links to, or null when it has no link of its own. */
export function linkFor(id, { content: c }) {
  if (['masthead', 'about', 'classifieds'].includes(id)) return c.site;
  if (id === 'activity') return `https://github.com/${c.login}`;
  if (id.startsWith('project-')) return c.projects.find((p) => `project-${p.id}` === id)?.url ?? null;
  if (id.startsWith('biz-')) return c.business.find((b) => `biz-${b.id}` === id)?.url ?? null;
  return null;
}

/** Alt text: the piece's own words, in reading order, without markup. */
export function altFor(id, { content: c, edition: e, weather: w, activity: a }) {
  if (id === 'masthead') return `${c.masthead.title}. Vol. ${e.volume}, No. ${e.issue}. ${e.dateLabel}.`;
  if (id === 'about') return join(`${c.about.kicker}: ${c.name}, ${c.about.role}`, c.about.text);
  if (id === 'activity') {
    return join(`Markets: ${a.headline}`, `${num(a.total)} contributions in the last year`, `${num(a.allTime)} all-time`,
      `Active on ${num(a.activeDays)} of ${num(a.dayCount)} days`, `Longest streak: ${num(a.longestStreak)} days`,
      `Current streak: ${num(a.currentStreak)} days`, a.bestMonth && `Best month: ${a.bestMonth.long}, with ${num(a.bestMonth.count)}`);
  }
  if (id.startsWith('project-')) { const p = c.projects.find((x) => `project-${x.id}` === id); return join(p.headline, p.body); }
  if (id.startsWith('biz-')) { const b = c.business.find((x) => `biz-${x.id}` === id); return join(`${b.name}: ${b.body}`, urlLabel(b.url).replace(/ →$/, '')); }
  if (id === 'classifieds') return join('Classifieds', c.classifieds.text);
  if (id === 'weather') {
    const legend = [...w.top.map((x) => `${x.name} ${x.pct}%`), w.otherPct ? `Other ${w.otherPct}%` : ''].filter(Boolean).join(', ');
    return join('Weather', `Forecast: ${w.forecast}`, legend);
  }
  throw new Error(`no alt text for piece ${id}`);
}

const width = (span) => `${Number(((span / 12) * 100).toFixed(2))}%`;

/** README.md: one paragraph, pieces inline with no whitespace, <br> between rows (docs/superpowers/notes/seam-spike.md). */
export function buildReadme(pieces, model) {
  const files = new Map(pieces.map((p) => [p.id, p.file]));
  const rows = ROWS.map((row) => row.map(({ id, span }) => {
    if (!files.has(id)) throw new Error(`missing image for piece ${id}`);
    const head = SECTION_HEADS[id] && model.content.sections[SECTION_HEADS[id]];
    const alt = head ? join(`${head.title}: ${head.tagline}`, altFor(id, model)) : altFor(id, model);
    const img = `<img src="img/${files.get(id)}" width="${width(span)}" alt="${attr(alt)}">`;
    const href = linkFor(id, model);
    return href ? `<a href="${attr(href)}">${img}</a>` : img;
  }).join(''));
  const { site, linkedin } = model.content;
  return [
    '<!-- Generated by scripts/render.js from content.yml. Edit content.yml, not this file. -->',
    `<p>${rows.join('<br>')}</p>`,
    '',
    `<p align="center"><a href="${attr(site)}">${attr(new URL(site).host)}</a> · <a href="${attr(linkedin)}">LinkedIn</a></p>`,
    '',
  ].join('\n');
}
